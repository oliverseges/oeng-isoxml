export type TranslationKey =
  keyof (typeof translations)[typeof DEFAULT_LOCALE] | string;

export function createI18n(locale: SupportedLocale) {
  const messages = {
    ...(translations[locale] ?? translations[DEFAULT_LOCALE]),
    ...supplementalTranslations[locale],
    ...csvHeaderTranslations[locale],
    ...issueMessageTranslations[locale],
    ...runtimeAndMeasurementTranslations[locale],
  } as Record<string, TranslationValue>;
  const fallbackMessages = {
    ...translations[DEFAULT_LOCALE],
    ...supplementalTranslations[DEFAULT_LOCALE],
    ...csvHeaderTranslations[DEFAULT_LOCALE],
    ...issueMessageTranslations[DEFAULT_LOCALE],
    ...runtimeAndMeasurementTranslations[DEFAULT_LOCALE],
  } as Record<string, TranslationValue>;
  const formatNumber = (value: number, options?: Intl.NumberFormatOptions) =>
    new Intl.NumberFormat(locale, options).format(value);
  const plural = (count: number, singular: string, pluralLabel: string) =>
    count === 1 ? singular : pluralLabel;
  const formatInteger = (value: number) =>
    formatNumber(value, { maximumFractionDigits: 0 });

  return {
    locale,
    t(key: TranslationKey, params: TranslationParams = {}) {
      const value = messages[key] ?? fallbackMessages[key];
      if (typeof value === "function") {
        return value(params, { formatNumber, plural });
      }
      const template = value ?? String(key);
      return template.replace(/\{(\w+)\}/g, (_match: string, name: string) =>
        String(params[name] ?? `{${name}}`),
      );
    },
    formatNumber,
    formatInteger,
    formatDateTime(value: number | Date, options?: Intl.DateTimeFormatOptions) {
      return new Intl.DateTimeFormat(locale, {
        dateStyle: "medium",
        timeStyle: "short",
        ...options,
      }).format(value);
    },
    formatTime(value: number | Date, options?: Intl.DateTimeFormatOptions) {
      return new Intl.DateTimeFormat(locale, {
        hour: "2-digit",
        minute: "2-digit",
        ...options,
      }).format(value);
    },
    formatFileSize(bytes: number) {
      return `${formatInteger(bytes)} B`;
    },
  };
}

export type I18n = ReturnType<typeof createI18n>;
