export type SupportedLocale = "en" | "da" | "pl" | "sv" | "de";

export const DEFAULT_LOCALE: SupportedLocale = "en";

export const SUPPORTED_LOCALES = [
  { code: "en", label: "English" },
  { code: "da", label: "Dansk" },
  { code: "pl", label: "Polski" },
  { code: "sv", label: "Svenska" },
  { code: "de", label: "Deutsch" },
] as const satisfies ReadonlyArray<{
  code: SupportedLocale;
  label: string;
}>;

const supportedLocaleCodes = new Set<SupportedLocale>(
  SUPPORTED_LOCALES.map((entry) => entry.code),
);

export function normalizeSupportedLocale(
  locale: string | null | undefined,
): SupportedLocale | undefined {
  if (!locale) return undefined;
  const normalized = locale.trim().toLowerCase().split(/[-_]/)[0];
  return supportedLocaleCodes.has(normalized as SupportedLocale)
    ? (normalized as SupportedLocale)
    : undefined;
}

export function detectPreferredLocale(
  candidates?: readonly string[],
): SupportedLocale {
  const languages =
    candidates ??
    (typeof navigator === "undefined"
      ? []
      : [
          ...(Array.isArray(navigator.languages) ? navigator.languages : []),
          navigator.language,
        ]);
  for (const candidate of languages) {
    const locale = normalizeSupportedLocale(candidate);
    if (locale) return locale;
  }
  return DEFAULT_LOCALE;
}

